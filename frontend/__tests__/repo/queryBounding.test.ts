/**
 * Every collection SELECT is bounded — checked one query at a time.
 *
 * ## The false green this replaces
 *
 * `dataLayerBoundary` asked whether a repository FILE contained a `.limit()`,
 * a `fetchPage`, a `.gte()` or a single-row terminal. A file with one
 * paginated query and one unbounded query passed, because the bounded one
 * satisfied the whole file. The gate looked like it measured bounding and
 * measured "is anything in here bounded".
 *
 * Each `supabase.from(...)` chain is now walked to its own terminator and
 * classified alone, so two queries in one file get two verdicts and
 * `UNCLASSIFIED` is a failure rather than an absence.
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import { stripComments } from '../helpers/sourceText';
import { extractChains, keysetOperations, type BoundKind } from '../helpers/queryChains';

const ROOT = join(__dirname, '..', '..');
const REPO_DIR = join(ROOT, 'repositories');

const files = readdirSync(REPO_DIR).filter((f) => f.endsWith('.ts'));

type Row = {
  repository: string;
  operation: string;
  table: string;
  bound: BoundKind;
  userScoped: boolean;
};

const collectionRows: Row[] = [];
const allRows: Row[] = [];

for (const file of files) {
  const src = stripComments(readFileSync(join(REPO_DIR, file), 'utf8'));

  for (const c of extractChains(src)) {
    const row: Row = {
      repository: file, operation: c.operation, table: c.table,
      bound: c.bound, userScoped: c.userScoped,
    };
    allRows.push(row);
    if (c.isCollection) collectionRows.push(row);
  }

  // `fetchPage` chains live in shared.ts; the repositories that call it are
  // keyset-paginated by delegation.
  for (const k of keysetOperations(src)) {
    const row: Row = {
      repository: file, operation: k.operation, table: k.table,
      bound: 'KEYSET_PAGE', userScoped: true,
    };
    allRows.push(row);
    collectionRows.push(row);
  }
}

describe('the extractor works (everything below depends on it)', () => {
  it('separates two chains in one file', () => {
    const src = `
      export async function a() {
        const x = await supabase.from('notes').select('*').eq('user_id', u).limit(10);
      }
      export async function b() {
        const y = await supabase.from('notes').select('*').eq('user_id', u);
      }`;
    const chains = extractChains(src);
    expect(chains).toHaveLength(2);
    expect(chains[0].bound).toBe('BOUNDED_DOMAIN_WINDOW');
    expect(chains[1].bound).toBe('UNCLASSIFIED');
  });

  it('is not fooled by a comma inside an or() filter', () => {
    const src = `const q = await supabase.from('t').select('*').or('a.lt.1,and(b.eq.2)').limit(5);`;
    const chains = extractChains(src);
    expect(chains).toHaveLength(1);
    expect(chains[0].bound).toBe('BOUNDED_DOMAIN_WINDOW');
  });

  it('does not treat a write as a collection read', () => {
    const src = `const q = await supabase.from('t').insert(row).select('*');`;
    expect(extractChains(src)[0].isCollection).toBe(false);
  });

  it('found real queries in the repositories (scanner sanity)', () => {
    expect(allRows.length).toBeGreaterThan(25);
    expect(collectionRows.length).toBeGreaterThan(10);
  });
});

describe('every collection SELECT is bounded', () => {
  it('none is UNCLASSIFIED', () => {
    const unbounded = collectionRows
      .filter((r) => r.bound === 'UNCLASSIFIED')
      .map((r) => `${r.repository}::${r.operation} -> ${r.table}`);
    expect(unbounded).toEqual([]);
  });

  it('every collection SELECT is scoped to the owner', () => {
    // A bound without a scope is a paginated view of everyone's rows.
    const unscoped = collectionRows
      .filter((r) => !r.userScoped && r.bound !== 'KEYSET_PAGE')
      .map((r) => `${r.repository}::${r.operation} -> ${r.table}`);
    expect(unscoped).toEqual([]);
  });
});

/**
 * Writes `docs/QUERY_BOUNDING_MATRIX.md` from the same data the assertions
 * use, so the document cannot drift from the code it describes.
 */
describe('the matrix document is generated from the code', () => {
  it('writes one row per query', () => {
    const lines = [
      '# ATLAS — QUERY BOUNDING MATRIX',
      '',
      '**Generated by `__tests__/repo/queryBounding.test.ts` — do not edit by hand.**',
      '',
      'One row per `supabase.from(...)` chain in `repositories/`, classified',
      'individually. A file-level check would pass a repository whose second',
      'query is unbounded; this does not.',
      '',
      '| Repository | Operation | Table | Collection? | Bound | User scoped |',
      '|---|---|---|---|---|---|',
      ...allRows
        .slice()
        .sort((a, b) => (a.repository + a.operation).localeCompare(b.repository + b.operation))
        .map((r) => {
          const isColl = collectionRows.includes(r) ? 'yes' : 'no';
          return `| \`${r.repository}\` | \`${r.operation}\` | \`${r.table}\` | ${isColl} | ${r.bound} | ${r.userScoped ? 'yes' : '—'} |`;
        }),
      '',
      '## Totals',
      '',
      `- queries: **${allRows.length}**`,
      `- collection SELECTs: **${collectionRows.length}**`,
      ...(['KEYSET_PAGE', 'DATE_WINDOW', 'BOUNDED_SEARCH', 'EXACT_COUNT', 'BOUNDED_DOMAIN_WINDOW', 'SINGLE_ROW'] as BoundKind[])
        .map((k) => `- ${k}: **${allRows.filter((r) => r.bound === k).length}**`),
      `- **UNCLASSIFIED: ${allRows.filter((r) => r.bound === 'UNCLASSIFIED').length}**`,
      '',
    ].join('\n');
    writeFileSync(join(ROOT, '..', 'docs', 'QUERY_BOUNDING_MATRIX.md'), lines, 'utf8');
    expect(lines).toContain('UNCLASSIFIED: 0');
  });
});
